#!/usr/bin/env node
/**
 * Generates `src/lang/mod.rs` (module list + registry) and a compiling stub
 * for every language module that does not exist yet, from the JavaScript
 * n2words repository's `src/` and `LANGUAGES.md`.
 *
 * Usage: node scripts/gen-lang-stubs.mjs <path-to-js-n2words-repo>
 *
 * Existing `src/lang/*.rs` files are never overwritten. Also writes
 * `scripts/languages.json` (code, module, kind, target, name) for tooling.
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const [, , jsRepo] = process.argv
if (!jsRepo) {
  console.error('usage: node scripts/gen-lang-stubs.mjs <path-to-js-n2words-repo>')
  process.exit(1)
}

const srcDir = resolve(jsRepo, 'src')
const languagesMd = readFileSync(resolve(jsRepo, 'LANGUAGES.md'), 'utf8')

// Names: "|`code`|Name|..." rows of the variants table, plus "|[`xx`](#...)|Name|" rows of the families table.
const names = new Map()
for (const m of languagesMd.matchAll(/^\|`([A-Za-z-]+)`\|([^|]+)\|/gm)) names.set(m[1], m[2].trim())
for (const m of languagesMd.matchAll(/^\|\[`([a-z]+)`\]\([^)]*\)\|([^|]+)\|/gm)) names.set(m[1], m[2].trim())

const moduleName = code => code.toLowerCase().replace(/-/g, '_')

const entries = []
for (const file of readdirSync(srcDir).filter(f => f.endsWith('.js')).sort()) {
  const code = file.slice(0, -3)
  const source = readFileSync(join(srcDir, file), 'utf8')
  const alias = source.match(/export const aliasOf = '([^']+)'/)
  const variant = source.match(/export const variantOf = '([^']+)'/)
  const kind = alias ? 'alias' : variant ? 'profile' : 'full'
  const target = alias ? alias[1] : variant ? variant[1] : null
  const name = names.get(code)
  if (!name) throw new Error(`no display name found for ${code} in LANGUAGES.md`)
  entries.push({ code, module: moduleName(code), kind, target, name })
}
// Registry order is by code (byte order), so `ar` sorts before `ar-SA`.
entries.sort((a, b) => (a.code < b.code ? -1 : a.code > b.code ? 1 : 0))

const outDir = resolve('src/lang')
let created = 0
for (const { code, module, kind, target, name } of entries) {
  const path = join(outDir, module + '.rs')
  if (existsSync(path)) continue
  const kindExpr = kind === 'alias'
    ? `Kind::Alias { target: "${target}" }`
    : kind === 'profile'
      ? `Kind::Profile { base: "${target}" }`
      : 'Kind::Full'
  writeFileSync(path, `//! ${name} (\`${code}\`).
//!
//! **Not yet ported** — this is a placeholder so the registry compiles.

use crate::language::{Kind, Language};

/// Registry entry for \`${code}\`.
pub static LANGUAGE: Language = Language {
    code: "${code}",
    name: "${name}",
    kind: ${kindExpr},
    cardinal: None,
    ordinal: None,
    currency: None,
};
`)
  created++
}

const mods = entries.map(e => `pub mod ${e.module};`).join('\n')
const registry = entries.map(e => `    &${e.module}::LANGUAGE,`).join('\n')
writeFileSync(join(outDir, 'mod.rs'), `//! One module per language entry point, named after its BCP 47 code in
//! snake_case (\`en_us\` for \`en-US\`, \`zh_hans_cn\` for \`zh-Hans-CN\`).
//!
//! Generated by \`scripts/gen-lang-stubs.mjs\`; the module list and the
//! registry below are the only two places that must know every language.

use crate::language::Language;

${mods}

/// Every entry point the crate ships, sorted by BCP 47 code.
pub static LANGUAGES: &[&Language] = &[
${registry}
];
`)

writeFileSync(resolve('scripts/languages.json'), JSON.stringify(entries, null, 2) + '\n')
console.log(`${entries.length} entry points; created ${created} stubs; wrote src/lang/mod.rs and scripts/languages.json`)
